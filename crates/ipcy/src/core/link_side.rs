//! Port of `ipcz/link_side.{h,cc}`.

use std::fmt;

/// An A/B enum to consistently distinguish between two sides of a single
/// conceptual link between nodes or routers. Each side of a link identifies as
/// the opposite of the other side.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
#[repr(u8)]
pub enum LinkSide {
    #[default]
    A = 0,
    B = 1,
}

impl LinkSide {
    // For generated message validation code.
    pub const MIN_VALUE: LinkSide = LinkSide::A;
    pub const MAX_VALUE: LinkSide = LinkSide::B;

    pub fn is_side_a(self) -> bool {
        self == LinkSide::A
    }

    pub fn is_side_b(self) -> bool {
        self == LinkSide::B
    }

    pub fn opposite(self) -> LinkSide {
        match self {
            LinkSide::A => LinkSide::B,
            LinkSide::B => LinkSide::A,
        }
    }
}

impl fmt::Display for LinkSide {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(if self.is_side_a() { "A" } else { "B" })
    }
}

/// The bit which is set on any generated buffer or sublink ID if the ID was
/// generated by side B of the NodeLink to which the buffer or sublink is
/// scoped. IDs generated by side A do not set this bit.
pub const LINK_SIDE_B_ID_BIT: u32 = 63;

/// Formats an ID for logging: the numeric value of the lower bits with an A or
/// B suffix to represent the high bit.
pub(super) fn fmt_side_tagged_id(value: u64, f: &mut fmt::Formatter<'_>) -> fmt::Result {
    const ID_MASK: u64 = (1 << LINK_SIDE_B_ID_BIT) - 1;
    write!(
        f,
        "{}{}",
        value & ID_MASK,
        if value >> LINK_SIDE_B_ID_BIT != 0 { ".B" } else { ".A" }
    )
}

impl super::message::WireEnum for LinkSide {
    type Raw = u8;
    const MAX_VALUE: u32 = LinkSide::MAX_VALUE as u32;

    fn from_raw(raw: u8) -> Option<Self> {
        match raw {
            0 => Some(LinkSide::A),
            1 => Some(LinkSide::B),
            _ => None,
        }
    }

    fn to_raw(self) -> u8 {
        self as u8
    }
}
